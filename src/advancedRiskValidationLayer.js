/**
 * Audit multiple fixtures and classify into TIER A, TIER B, TIER C (Layer 19).
 * 
 * @param {Array} fixtures - Array of match fixtures
 * @returns {Object} Tiered multi-fixture classification
 */
export function auditMultipleFixtures(fixtures = []) {
  const auditedList = (fixtures || []).map(f => auditFixturePrediction(f));

  const tierA = auditedList.filter(a => 
    a.verdictCode === 'CONFIRMED' &&
    a.layer2_dataQuality?.qualityGrade === 'HIGH' &&
    (a.layer12_contradictionEngine?.contradictionLevel === 'NONE' || a.layer12_contradictionEngine?.contradictionLevel === 'LOW')
  );

  const tierB = auditedList.filter(a =>
    a.verdictCode === 'CONFIRMED_WITH_CAUTION' ||
    (a.verdictCode === 'CONFIRMED' && !tierA.some(t => t.fixture === a.fixture))
  );

  const tierC = auditedList.filter(a =>
    a.verdictCode === 'WATCH' || a.verdictCode === 'NO_BET'
  );

  return {
    totalAudited: auditedList.length,
    tierA_strongest: tierA,
    tierB_acceptable: tierB,
    tierC_avoid: tierC,
    tierACount: tierA.length,
    tierBCount: tierB.length,
    tierCCount: tierC.length,
    zeroTierAPolicyEnforced: tierA.length === 0,
    auditedMatches: auditedList
  };
}
